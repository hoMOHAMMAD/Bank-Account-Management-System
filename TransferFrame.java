    private void loadCurrentAccount() {

        if (currentUser == null) {
            return;
        }

        dao.AccountDAO accountDAO = new dao.AccountDAO();

        currentAccount = accountDAO.getFirstAccountByUserId(currentUser.getUserId());

        if (currentAccount == null) {
            fromAccountIdTxt.setText("");
            return;
        }

        fromAccountIdTxt.setText(String.valueOf(currentUser.getUserId()));
        fromAccountIdTxt.setEditable(false);
    }

    private void transferBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_transferBtnActionPerformed
        // TODO add your handling code here:
        if (currentUser == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Kullanıcı bulunamadı!");
            return;
        }

        try {
            int receiverUserId = Integer.parseInt(toAccountIdTxt.getText());
            double amount = Double.parseDouble(amountSpinner.getValue().toString());

            if (receiverUserId == currentUser.getUserId()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Kendi hesabınıza transfer yapamazsınız!");
                return;
            }

            dao.TransactionDAO transactionDAO = new dao.TransactionDAO();

            boolean result = transactionDAO.transferByUserId(
                    currentUser.getUserId(),
                    receiverUserId,
                    amount
            );

            if (result) {
                javax.swing.JOptionPane.showMessageDialog(this, "Transfer başarılı!");
                loadCurrentAccount();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Alıcı kullanıcı hesabı bulunamadı!");
            }

        } catch (exceptions.InvalidAmountException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Transfer Hatası",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Geçersiz giriş!");
        }
    }//GEN-LAST:event_transferBtnActionPerformed

