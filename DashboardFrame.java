    private void loadUserTransactions() {

        if (currentUser == null) {
            return;
        }

        dao.TransactionDAO transactionDAO = new dao.TransactionDAO();

        java.util.ArrayList<models.Transaction> transactions
                = transactionDAO.getTransactionsByUserId(currentUser.getUserId());

        javax.swing.DefaultListModel<String> model
                = new javax.swing.DefaultListModel<>();

        for (models.Transaction t : transactions) {

            String type = t.getTransactionType();

            if (type.equalsIgnoreCase("Deposit")) {
                type = "Para Yatırma";
            } else if (type.equalsIgnoreCase("Withdraw")) {
                type = "Para Çekme";
            } else if (type.equalsIgnoreCase("Transfer")) {
                type = "Havale / EFT";
            }

            model.addElement(
                    "İşlem ID: " + t.getTransactionId()
                    + " | İşlem Türü: " + type
                    + " | Tutar: " + t.getAmount()
                    + " | Tarih: " + t.getTransactionDate()
            );
        }

        jList1.setModel(model);
    }

