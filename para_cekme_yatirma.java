    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (currentAccount == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Hesap bulunamadı!");
            return;
        }

        try {
            double amount = Double.parseDouble(jTextField1.getText());

            dao.TransactionDAO transactionDAO = new dao.TransactionDAO();

            boolean result = transactionDAO.withdraw(
                    currentAccount.getAccountId(),
                    amount
            );

            if (result) {
                javax.swing.JOptionPane.showMessageDialog(this, "Para çekme başarılı!");
                loadCurrentAccount();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Para çekme başarısız");
            }

        } catch (exceptions.InvalidAmountException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Geçersiz tutar");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (currentAccount == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Hesap bulunamadı");
            return;
        }

        try {
            double amount = Double.parseDouble(jTextField1.getText());

            dao.TransactionDAO transactionDAO = new dao.TransactionDAO();

            boolean result = transactionDAO.deposit(
                    currentAccount.getAccountId(),
                    amount
            );

            if (result) {
                javax.swing.JOptionPane.showMessageDialog(this, "Para yatırma başarılı!!");
                loadCurrentAccount();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Para yatırma başarısız");
            }

        } catch (exceptions.InvalidAmountException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Geçersiz tutar");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

