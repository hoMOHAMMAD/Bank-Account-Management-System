    private void loadCurrentAccount() {
        dao.AccountDAO accountDAO = new dao.AccountDAO();

        java.util.ArrayList<models.Account> accounts
                = accountDAO.getAccountsByUserId(currentUser.getUserId());

        if (accounts.isEmpty()) {
            jLabel1.setText("Available cash: 0 TL");
            currentAccount = null;
            return;
        }

        currentAccount = accounts.get(0);

        jLabel1.setText("Available cash: "
                + currentAccount.getBalance()
                + " "
                + currentAccount.getCurrency());
    }

